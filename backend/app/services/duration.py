"""時間量の単位変換（仕様書6.3「時間の単位と表示規則」、10章バリデーション方針）。

算出・保持の正準単位は分（整数）とする。時間（hour）は表示のためだけに用いる派生値であり、
**小数第2位以下を切り捨てて小数第1位まで**とする（四捨五入しない）。例: 50分は
0.8333…時間ではなく 0.8時間 と表示する。

切り捨ての規則をここ1箇所に集約するのは、同じ規則がバックエンドの各所とフロントエンドに
二重実装されるのを避けるため（CLAUDE.md DRYの原則）。フロントエンドへは本モジュールで
換算済みの値を返し、フロント側では再換算しない。
"""

#: 1時間あたりの分数。
MINUTES_PER_HOUR = 60

#: 表示に残す小数桁数（小数第1位まで）。
_DISPLAY_DECIMAL_PLACES = 1
_DISPLAY_SCALE = 10**_DISPLAY_DECIMAL_PLACES


def to_display_hours(minutes: int) -> float:
    """分を表示用の時間へ換算する（小数第2位以下は切り捨て）。

    浮動小数点の乗除を経由すると 0.7 が 0.6999... となり切り捨てが1つずれることがあるため、
    整数演算のみで桁を落としてから最後に一度だけ除算する。
    """
    return minutes * _DISPLAY_SCALE // MINUTES_PER_HOUR / _DISPLAY_SCALE


def to_exact_hours(minutes: int) -> float:
    """分を時間へ換算する（切り捨てなし）。

    実効速度・必要速度は「分量／時間」を単位とする（ロジック・プロンプト編8.1）。これらの
    算出では表示用の切り捨てを行わず、分をそのまま時間へ換算した値を用いる。
    """
    return minutes / MINUTES_PER_HOUR

def _prompt_template_table() -> sa.Table:
    return sa.table(
        "prompt_template",
        sa.column("purpose", sa.String),
        sa.column("body", sa.Text),
        sa.column("is_customized", sa.Boolean),
        sa.column("updated_at", sa.DateTime),
    )


def upgrade() -> None:
    """Upgrade schema.

    週次要約がまだ無い過去日の実績・日記を送る{{recent_logs}}を資格試験の日次報告
    フィードバックへ追加する（S04 G2）。f7c3e9a1b5d6・7f4f5e089f3aと同じく
    is_customized=False（利用者が未編集）の行のみを対象とし、利用者が編集済みの
    テンプレートは上書きしない（{{recent_logs}}は注入されないまま残る）。
    """
    bind = op.get_bind()
    prompt_template = _prompt_template_table()
    now = datetime.now(UTC)
    bind.execute(
        prompt_template.update()
        .where(
            prompt_template.c.purpose == "DAILY_FEEDBACK",
            prompt_template.c.is_customized.is_(False),
        )
        .values(body=_NEW_DAILY_FEEDBACK_BODY, updated_at=now)
    )



_prompt_template = sa.table(
    "prompt_template",
    sa.column("purpose", sa.String),
    sa.column("body", sa.Text),
    sa.column("is_customized", sa.Boolean),
    sa.column("updated_at", sa.DateTime),
)


def _set_daily_feedback_body(body: str) -> None:
    """is_customized=False（利用者が未編集）の行のみを更新する（利用者の編集を上書きしない）。"""
    bind = op.get_bind()
    bind.execute(
        _prompt_template.update()
        .where(
            _prompt_template.c.purpose == "DAILY_FEEDBACK",
            _prompt_template.c.is_customized.is_(False),
        )
        .values(body=body, updated_at=datetime.now(UTC))
    )



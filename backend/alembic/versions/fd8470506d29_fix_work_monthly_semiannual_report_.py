def _prompt_template_table() -> sa.Table:
    return sa.table(
        "prompt_template",
        sa.column("purpose", sa.String),
        sa.column("body", sa.Text),
        sa.column("is_customized", sa.Boolean),
        sa.column("updated_at", sa.DateTime),
    )


def upgrade() -> None:
    """Upgrade schema.

    月次報告・半期評価（17.9・17.10）の達成度スケールを反転（1が最高評価→5が最高評価）
    し、自由記述の各節へ「：」区切りで複数項目を列記するルールを追加する。f7c3e9a1b5d6等
    と同じくis_customized=False（利用者が未編集）の行のみを対象とし、利用者が編集済みの
    テンプレートは上書きしない。
    """
    bind = op.get_bind()
    prompt_template = _prompt_template_table()
    now = datetime.now(UTC)
    bind.execute(
        prompt_template.update()
        .where(
            prompt_template.c.purpose == "GOAL_RETROSPECTIVE_WORK_MONTHLY",
            prompt_template.c.is_customized.is_(False),
        )
        .values(body=_NEW_GOAL_RETROSPECTIVE_WORK_MONTHLY_BODY, updated_at=now)
    )
    bind.execute(
        prompt_template.update()
        .where(
            prompt_template.c.purpose == "GOAL_RETROSPECTIVE_WORK_SEMIANNUAL",
            prompt_template.c.is_customized.is_(False),
        )
        .values(body=_NEW_GOAL_RETROSPECTIVE_WORK_SEMIANNUAL_BODY, updated_at=now)
    )


